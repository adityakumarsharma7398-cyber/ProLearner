import { useMemo, useState } from 'react'
import Card from '../components/Card.jsx'
import Button from '../components/Button.jsx'
import { deriveStatuses, STATUS_LABEL, PASS_MARK, XP_PER_TOPIC } from '../engine/progress.js'
import { getTopicContent } from '../engine/content.js'

export default function TopicView({ roadmap, topicId, onPass, onNavigate, onOpenTopic }) {
  const topic = roadmap?.topics.find((t) => t.id === topicId)
  const [phase, setPhase] = useState('learn') // learn | quiz | result
  const [qi, setQi] = useState(0)
  const [picked, setPicked] = useState(null)
  const [checked, setChecked] = useState(false)
  const [answers, setAnswers] = useState([])
  const [result, setResult] = useState(null)

  const content = useMemo(() => (topic ? getTopicContent(roadmap, topic) : null), [roadmap?.id, topicId])

  if (!roadmap || !topic) {
    return (
      <div className="container stack">
        <Card tone="peach">
          <h1>Topic not found</h1>
          <p>Create a roadmap on the dashboard first.</p>
          <Button onClick={() => onNavigate('dashboard')}>Back to dashboard</Button>
        </Card>
      </div>
    )
  }

  const statuses = deriveStatuses(roadmap)
  const status = statuses[topic.id]
  const milestone = roadmap.milestones.find((m) => m.id === topic.milestoneId)
  const byId = Object.fromEntries(roadmap.topics.map((t) => [t.id, t]))
  const quiz = content.quiz
  const nextTopic = roadmap.progress.currentTopicId ? byId[roadmap.progress.currentTopicId] : null

  const startQuiz = () => {
    setQi(0); setPicked(null); setChecked(false); setAnswers([]); setResult(null); setPhase('quiz')
  }

  const check = () => {
    setChecked(true)
    setAnswers([...answers, picked === quiz[qi].answer])
  }

  const advance = () => {
    if (qi < quiz.length - 1) {
      setQi(qi + 1); setPicked(null); setChecked(false)
      return
    }
    const correct = answers.filter(Boolean).length
    const pct = Math.round((correct / quiz.length) * 100)
    const passed = pct >= PASS_MARK
    const wasDone = status === 'completed'
    const { xpAwarded } = passed ? onPass(topic.id) : { xpAwarded: 0 }
    const missed = quiz.filter((_, i) => !answers[i])
    setResult({ correct, pct, passed, xpAwarded, wasDone, missed })
    setPhase('result')
  }

  const header = (
    <Card tone="yellow">
      <div className="row-between">
        <div>
          <span className={`pill pill--${status}`}>{STATUS_LABEL[status]}</span>
          <h1 style={{ marginTop: '.5rem', ...(phase === 'quiz' ? { fontSize: '1.6rem', marginBottom: 0 } : {}) }}>{topic.name}</h1>
          {phase !== 'quiz' && <p style={{ marginBottom: 0 }}>{topic.objective}</p>}
        </div>
        {phase !== 'quiz' && <div className="btn-col">
          <Button variant="ghost" onClick={() => onNavigate('dashboard')}>Dashboard</Button>
          <Button variant="ghost" onClick={() => onNavigate('journey')}>Open Progress Journey</Button>
          <Button variant="ghost" onClick={() => onNavigate('map')}>Open Knowledge Map</Button>
        </div>}
      </div>
    </Card>
  )

  if (status === 'locked') {
    const missing = topic.prerequisites.filter((p) => statuses[p] !== 'completed')
    return (
      <div className="container stack">
        {header}
        <Card tone="peach">
          <h2>This topic is locked</h2>
          <p>Complete these prerequisites first:</p>
          <ul className="link-list">
            {missing.map((p) => (
              <li key={p}><button type="button" className="link-btn" onClick={() => onOpenTopic(p)}>{byId[p].name}</button> ({STATUS_LABEL[statuses[p]].toLowerCase()})</li>
            ))}
          </ul>
        </Card>
      </div>
    )
  }

  if (phase === 'learn') {
    return (
      <div className="container stack">
        {header}
        <div className="grid grid-2">
          <Card tone="mint">
            <h2>Learning notes</h2>
            <ul className="notes">
              {content.notes.map((n) => <li key={n}>{n}</li>)}
            </ul>
            <p className="small" style={{ color: 'var(--ink)' }}>
              {content.source === 'handwritten'
                ? 'Demo notes written for this prototype, not generated by AI.'
                : 'No written lesson exists for this topic yet. The quiz below is a self-check built from your roadmap structure, not subject-expert content, and nothing here is AI-generated.'}
            </p>
          </Card>
          <Card>
            <h2>Topic details</h2>
            <dl className="facts">
              <dt>Milestone</dt><dd>{milestone.order}. {milestone.title}</dd>
              <dt>Prerequisites</dt>
              <dd>{topic.prerequisites.length ? topic.prerequisites.map((p) => byId[p].name).join(', ') : 'None. A starting topic.'}</dd>
              <dt>Estimated study time</dt><dd>about {topic.estimatedHours} hours</dd>
              <dt>Quiz</dt><dd>{quiz.length} questions, {PASS_MARK}% to pass, {XP_PER_TOPIC} XP the first time</dd>
            </dl>
            {status === 'completed' && <p className="notice" style={{ marginTop: '1rem' }}>Already completed. You can retake the quiz; XP is only awarded once.</p>}
            <p style={{ marginTop: '1rem', marginBottom: 0 }}><Button onClick={startQuiz}>Take the quiz</Button></p>
          </Card>
        </div>
      </div>
    )
  }

  if (phase === 'quiz') {
    const item = quiz[qi]
    return (
      <div className="container stack">
        {header}
        <Card>
          <p className="small">Question {qi + 1} of {quiz.length}</p>
          <div className="bar" aria-hidden="true"><div className="bar__fill" style={{ width: `${((qi + (checked ? 1 : 0)) / quiz.length) * 100}%` }} /></div>
          <h2 style={{ marginTop: '1rem' }}>{item.q}</h2>
          <div className="options" role="radiogroup" aria-label="Answer options">
            {item.options.map((opt, i) => {
              let cls = 'option'
              if (picked === i) cls += ' option--picked'
              if (checked && i === item.answer) cls += ' option--right'
              if (checked && picked === i && i !== item.answer) cls += ' option--wrong'
              return (
                <button key={opt} type="button" role="radio" aria-checked={picked === i} className={cls} disabled={checked} onClick={() => setPicked(i)}>
                  {opt}
                </button>
              )
            })}
          </div>
          {checked && (
            <p className={`notice ${picked === item.answer ? '' : 'notice--wrong'}`} role="status">
              {picked === item.answer ? 'Correct. ' : 'Not quite. '}{item.explain}
            </p>
          )}
          <p style={{ marginTop: '1rem', marginBottom: 0 }}>
            {!checked
              ? <Button onClick={check} disabled={picked === null}>Check answer</Button>
              : <Button onClick={advance}>{qi < quiz.length - 1 ? 'Next question' : 'See results'}</Button>}
          </p>
        </Card>
      </div>
    )
  }

  // result
  return (
    <div className="container stack">
      {header}
      <Card tone={result.passed ? 'mint' : 'pink'}>
        <h2>{result.passed ? 'You passed!' : 'Not passed yet'}</h2>
        <div className="stat-row">
          <span className="pill">{result.correct} of {quiz.length} correct</span>
          <span className="pill">{result.pct}% (pass mark {PASS_MARK}%)</span>
          {result.passed && <span className="pill">{result.xpAwarded ? `+${result.xpAwarded} XP` : 'No extra XP: already completed'}</span>}
        </div>

        {result.passed ? (
          <>
            <p>{result.wasDone ? 'This topic was already complete, so your progress is unchanged.' : 'Milestone topic completed. Your car has moved on.'}</p>
            {nextTopic ? (
              <p><strong>Next up:</strong> {nextTopic.name}</p>
            ) : (
              <p><strong>Roadmap complete.</strong> You have finished every topic.</p>
            )}
            <div className="btn-row">
              {nextTopic && nextTopic.id !== topic.id && <Button onClick={() => onOpenTopic(nextTopic.id)}>Start next topic</Button>}
              <Button variant="ghost" onClick={() => onNavigate('journey')}>Open Progress Journey</Button>
              <Button variant="ghost" onClick={() => onNavigate('map')}>Open Knowledge Map</Button>
            </div>
          </>
        ) : (
          <>
            <p>Your progress has not changed. Revise the notes below, then try again.</p>
            <ul className="notes">
              {result.missed.map((m) => <li key={m.q}><strong>Review:</strong> {m.q} {m.explain}</li>)}
            </ul>
            <div className="btn-row">
              <Button onClick={startQuiz}>Retry quiz</Button>
              <Button variant="ghost" onClick={() => setPhase('learn')}>Revise notes</Button>
              <Button variant="ghost" onClick={() => onNavigate('journey')}>Open Progress Journey</Button>
            </div>
          </>
        )}
      </Card>
    </div>
  )
}
